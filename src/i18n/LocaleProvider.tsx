interface LocaleValue {
  language: Language
  currency: Currency
  setLanguage: (language: Language) => void
  setCurrency: (currency: Currency) => void
  t: (text: string) => string
  formatNumber: (value: number) => string
}

const LocaleContext = createContext<LocaleValue>({ language: 'en', currency: 'GEL', setLanguage: () => undefined, setCurrency: () => undefined, t: (text) => text, formatNumber: (value) => value.toLocaleString('en-US') })

const readSetting = <Value extends string>(key: string, allowed: readonly Value[], fallback: Value): Value => {
  const stored = window.localStorage.getItem(key)
  return allowed.includes(stored as Value) ? stored as Value : fallback
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => readSetting('velora-language', ['en', 'ka'], 'en'))
  const [currency, setCurrency] = useState<Currency>(() => readSetting('velora-currency', ['GEL', 'USD'], 'GEL'))
  setMoneyPreferences(currency, language)

  useEffect(() => {
    window.localStorage.setItem('velora-language', language)
    document.documentElement.lang = language
  }, [language])

  useEffect(() => { window.localStorage.setItem('velora-currency', currency) }, [currency])

  const t = useCallback((text: string) => language === 'ka' ? translations[text] ?? text : text, [language])
  const formatNumber = useCallback((value: number) => value.toLocaleString(language === 'ka' ? 'ka-GE' : 'en-US'), [language])
  const value = useMemo(() => ({ language, currency, setLanguage, setCurrency, t, formatNumber }), [currency, formatNumber, language, t])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLocale() {
  return useContext(LocaleContext)
}
